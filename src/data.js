// Loads the household's world (profile, catalog, history, deals, slots, inbox) and the mutable demo state.
import { readFileSync, writeFileSync, existsSync, renameSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

export const DATA_DIR = process.env.PANTRY_DATA ?? fileURLToPath(new URL('../data/', import.meta.url));
export const STATE_FILE = process.env.PANTRY_STATE ?? join(DATA_DIR, 'state.json');

export function readJson(name, fallback) {
  const path = join(DATA_DIR, name);
  if (!existsSync(path)) {
    if (fallback !== undefined) return fallback;
    throw new Error(`Missing data file: ${path}`);
  }
  return JSON.parse(readFileSync(path, 'utf8'));
}

export function writeJson(name, value) {
  const path = join(DATA_DIR, name);
  writeFileSync(`${path}.tmp`, JSON.stringify(value, null, 2) + '\n');
  renameSync(`${path}.tmp`, path);
}

export function indexCatalog(doc) {
  const products = doc.products;
  const bySku = new Map(products.map(p => [p.sku, p]));
  return {
    ...doc,
    products,
    bySku,
    get: sku => bySku.get(sku),
    family: family => products.filter(p => p.family === family),
    byName: name => {
      const key = String(name).trim().toLowerCase();
      return products.find(p => p.name.toLowerCase() === key || (p.aliases ?? []).some(a => a.toLowerCase() === key));
    },
  };
}

export function loadWorld() {
  return {
    household: readJson('household.json'),
    catalog: indexCatalog(readJson('catalog.json')),
    history: readJson('history.json').orders,
    deals: readJson('deals.json').deals,
    slots: readJson('slots.json').slots,
    availability: readJson('availability.json', { unavailable: [] }),
    inbox: readJson('inbox.json').emails,
    inboxAddress: readJson('inbox.json').address,
    thread: readJson('thread.json').messages,
    threadSurfaces: readJson('thread.json').surfaces,
  };
}

export function freshState() {
  return {
    version: 1,
    clock: null,       // household clock (ISO); null = the scenario's starting moment
    messages: [],      // conversation in the app, appended to the cross-surface thread
    cartEdits: {},     // family -> { action: 'exclude' | 'include' | 'swap', sku? }
    preferences: {},   // family -> { from, to, reason, text, until? } — accepted deal switches and inbox learnings
    approvals: [],     // vault approvals, newest last
    orders: [],        // orders Pantry placed (become history once delivered)
    cases: [],         // drafted retailer cases, each needs approval to file
    inboxExtra: [],    // emails generated by Pantry's own actions (e.g. order confirmation)
    log: [],           // audit trail of every external write and its approval
  };
}

export function loadState() {
  if (!existsSync(STATE_FILE)) return freshState();
  try {
    return { ...freshState(), ...JSON.parse(readFileSync(STATE_FILE, 'utf8')) };
  } catch {
    return freshState();
  }
}

export function saveState(state) {
  writeFileSync(`${STATE_FILE}.tmp`, JSON.stringify(state, null, 2) + '\n');
  renameSync(`${STATE_FILE}.tmp`, STATE_FILE);
}
